mkdirSync(join(root, "themes"), { recursive: true });
// Preenche paleta ANSI, cores de UI e papéis de sintaxe com os padrões HX99.
function resolve(v) {
  const ansi = v.ansi ?? tangoAnsi;
  const p10k = { ...p10kColors, ...v.p10k };
  const syn = {
    string: ansi.brightGreen,
    number: ansi.brightYellow,
    constant: p10k.ubuntu,
    keyword: p10k.dirBright,
    function: ansi.brightBlue,
    type: ansi.brightCyan,
    parameter: ansi.brightMagenta,
    tag: ansi.brightRed,
    attribute: ansi.brightYellow,
    ...v.syn,
  };
  return { ...v, ansi, p10k, syn };
}

for (const variant of variants) {
  const v = resolve(variant);
  const theme = {
    $schema: "vscode://schemas/color-theme",
    name: v.name,
    type: "dark",
    semanticHighlighting: true,
    colors: { ...colors(v), ...v.overrides },
    tokenColors: tokenColors(v),
    semanticTokenColors: semanticTokenColors(v),
  };
  const out = join(root, "themes", v.file);
  writeFileSync(out, JSON.stringify(theme, null, 2) + "\n");
  console.log("✔ " + v.file);
}
